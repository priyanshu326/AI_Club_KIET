'''11 — for loop: Print each item in a list and then print that item multiplied by 2. '''

# Sample list of numbers
numbers = [10, 20, 30, 40, 50]

# Loop through each item in the list
for item in numbers:
    print("Item:", item)
    print("Multiplied by 2:", item * 2)
    print("-" * 20)  # Separator for readability