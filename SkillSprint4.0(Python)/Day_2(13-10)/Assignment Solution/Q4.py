'''4 — Nested lists: Given marks = [[85, 91, 89], [78, 81, 86], [62, 75, 77]], print the second student’s marks and the last student’s second mark. '''

marks = [[85, 91, 89], [78, 81, 86], [62, 75, 77]]


print("Second student's marks:", marks[1])


print("Last student's second mark:", marks[-1][1])