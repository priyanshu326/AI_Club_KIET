'''6 — Sequence comparison: Create a list, tuple, and string. For each one, print its length, its item at index 1, and a slice from index 1 onward. '''

# 1. List
my_list = [10, 20, 30, 40]
print("--- List ---")
print("Length:", len(my_list))
print("Item at index 1:", my_list[1])
print("Slice from index 1:", my_list[1:])

# 2. Tuple
my_tuple = ("apple", "banana", "cherry")
print("\n--- Tuple ---")
print("Length:", len(my_tuple))
print("Item at index 1:", my_tuple[1])
print("Slice from index 1:", my_tuple[1:])

# 3. String
my_string = "Python"
print("\n--- String ---")
print("Length:", len(my_string))
print("Item at index 1:", my_string[1])
print("Slice from index 1:", my_string[1:])